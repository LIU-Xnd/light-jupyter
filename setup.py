"""Keep the packaged README in step with the real one.

The README is the package's long_description, and the self-test reads it
to check that the documented flags and the number of checks are right.
An installed package has no README at its parent's path, so a copy has
to travel inside it -- but a second copy that nobody keeps in step is a
second copy that goes stale.

So it is generated at build time, from the one real README. setup.py is
used rather than a cmdclass hook because the build runs in an isolated
environment where a project-local module is not importable.
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "README.md")
DST = os.path.join(HERE, "lj", "README.md")
BANNER = ("<!-- generated by setup.py -- do not edit; "
          "edit README.md at the repository root -->\n")


def sync_readme():
    if not os.path.isfile(SRC):
        return
    with open(SRC, "r", encoding="utf-8") as fh:
        text = fh.read()
    new = BANNER + text
    old = None
    if os.path.isfile(DST):
        with open(DST, "r", encoding="utf-8") as fh:
            old = fh.read()
    if old != new:
        with open(DST, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)


sync_readme()

from setuptools import setup

setup()
